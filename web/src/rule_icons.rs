#[cfg(test)]
mod tests {
    use super::ICON_NAMES;
    use crate::catalog::catalog;

    #[test]
    fn every_rule_has_exactly_one_icon() {
        let rules = catalog();
        for rule in &rules {
            assert!(ICON_NAMES.contains(&rule.name), "{} has no icon", rule.name);
        }
        assert_eq!(ICON_NAMES.len(), rules.len(), "an icon names no rule");
    }
}
